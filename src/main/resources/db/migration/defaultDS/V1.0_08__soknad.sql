CREATE TABLE SOKNAD
(
    ID                 NUMERIC                  NOT NULL,
    SAKSNUMMER         VARCHAR(50)              NOT NULL,
    MOTTATT_TIDSPUNKT  TIMESTAMP WITH TIME ZONE NOT NULL,
    ROLLE              VARCHAR(50)              NOT NULL,
    AKTIV              BOOLEAN                  NOT NULL,
    CONSTRAINT PK_SOKNAD PRIMARY KEY (ID)
);

CREATE SEQUENCE SEQ_SOKNAD MINVALUE 1000000 START WITH 1000000 INCREMENT BY 50 NO CYCLE;

CREATE UNIQUE INDEX UIDX_SOKNAD_AKTIV ON SOKNAD (SAKSNUMMER) WHERE AKTIV = TRUE;

CREATE TABLE SOKNAD_PERIODE
(
    ID                          NUMERIC     NOT NULL,
    SOKNAD_ID                   NUMERIC     NOT NULL,
    FOM                         DATE        NOT NULL,
    TOM                         DATE        NOT NULL,
    ROLLE                       VARCHAR(50) NOT NULL,
    KONTO_TYPE                  VARCHAR(50),
    UTSETTELSE_ARSAK            VARCHAR(50),
    OVERFORING_ARSAK            VARCHAR(50),
    MORS_AKTIVITET              VARCHAR(50),
    GRADERING_ARBEIDSTIDPROSENT NUMERIC,
    SAMTIDIG_UTTAKSPROSENT      NUMERIC,
    FLERBARNSDAGER              BOOLEAN,
    AKTIVITET_TYPE              VARCHAR(50),
    ARBEIDSGIVER_ID             VARCHAR(50),
    ARBEIDSGIVER_TYPE           VARCHAR(50),
    CONSTRAINT PK_SOKNAD_PERIODE PRIMARY KEY (ID),
    CONSTRAINT FK_SOKNAD_PERIODE_1 FOREIGN KEY (SOKNAD_ID) REFERENCES SOKNAD (ID)
);

CREATE SEQUENCE SEQ_SOKNAD_PERIODE MINVALUE 1000000 START WITH 1000000 INCREMENT BY 50 NO CYCLE;

CREATE INDEX IDX_SOKNAD_PERIODE_1 ON SOKNAD_PERIODE (SOKNAD_ID);

COMMENT ON TABLE SOKNAD IS 'Innsendt søknad om foreldrepenger';
COMMENT ON COLUMN SOKNAD.ID IS 'Teknisk identifikator for søknaden';
COMMENT ON COLUMN SOKNAD.SAKSNUMMER IS 'Saksnummer til søkers sak';
COMMENT ON COLUMN SOKNAD.MOTTATT_TIDSPUNKT IS 'Tidspunkt søknaden ble mottatt';
COMMENT ON COLUMN SOKNAD.ROLLE IS 'Rolle for søkeren';
COMMENT ON COLUMN SOKNAD.AKTIV IS 'Angir om søknaden er aktiv for saken';

COMMENT ON TABLE SOKNAD_PERIODE IS 'Uttaksperioder i en søknad';
COMMENT ON COLUMN SOKNAD_PERIODE.ID IS 'Teknisk identifikator for perioden';
COMMENT ON COLUMN SOKNAD_PERIODE.SOKNAD_ID IS 'Identifikator for søknaden perioden tilhører';
COMMENT ON COLUMN SOKNAD_PERIODE.FOM IS 'Periodens startdato';
COMMENT ON COLUMN SOKNAD_PERIODE.TOM IS 'Periodens sluttdato';
COMMENT ON COLUMN SOKNAD_PERIODE.ROLLE IS 'Rolle for perioden';
COMMENT ON COLUMN SOKNAD_PERIODE.KONTO_TYPE IS 'Type uttakskonto';
COMMENT ON COLUMN SOKNAD_PERIODE.UTSETTELSE_ARSAK IS 'Årsak til utsettelse';
COMMENT ON COLUMN SOKNAD_PERIODE.OVERFORING_ARSAK IS 'Årsak til overføring';
COMMENT ON COLUMN SOKNAD_PERIODE.MORS_AKTIVITET IS 'Mors aktivitet';
COMMENT ON COLUMN SOKNAD_PERIODE.GRADERING_ARBEIDSTIDPROSENT IS 'Arbeidstidsprosent ved gradering';
COMMENT ON COLUMN SOKNAD_PERIODE.SAMTIDIG_UTTAKSPROSENT IS 'Prosent for samtidig uttak';
COMMENT ON COLUMN SOKNAD_PERIODE.FLERBARNSDAGER IS 'Angir om perioden gjelder flerbarnsdager';
COMMENT ON COLUMN SOKNAD_PERIODE.AKTIVITET_TYPE IS 'Type aktivitet i perioden';
COMMENT ON COLUMN SOKNAD_PERIODE.ARBEIDSGIVER_ID IS 'Organisasjonsnummer for organisasjon eller fødselsnummer for privat arbeidsgiver';
COMMENT ON COLUMN SOKNAD_PERIODE.ARBEIDSGIVER_TYPE IS 'Type arbeidsgiver';
