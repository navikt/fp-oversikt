CREATE TABLE SOKNADSUTTAKSPLAN
(
    ID                 NUMERIC                  NOT NULL,
    SAKSNUMMER         VARCHAR(50)              NOT NULL,
    MOTTATT_TIDSPUNKT  TIMESTAMP WITH TIME ZONE NOT NULL,
    ROLLE              VARCHAR(50)              NOT NULL,
    AKTIV              BOOLEAN                  NOT NULL,
    CONSTRAINT PK_SOKNADSUTTAKSPLAN PRIMARY KEY (ID)
);

CREATE SEQUENCE SEQ_SOKNADSUTTAKSPLAN MINVALUE 1000000 START WITH 1000000 INCREMENT BY 50 NO CYCLE;

CREATE UNIQUE INDEX UIDX_SOKNADSUTTAKSPLAN_AKTIV ON SOKNADSUTTAKSPLAN (SAKSNUMMER) WHERE AKTIV = TRUE;

CREATE TABLE SOKNADSUTTAKSPLAN_PERIODE
(
    ID                          NUMERIC     NOT NULL,
    SOKNADSUTTAKSPLAN_ID        NUMERIC     NOT NULL,
    FOM                         DATE        NOT NULL,
    TOM                         DATE        NOT NULL,
    ROLLE                       VARCHAR(50) NOT NULL,
    KONTO_TYPE                  VARCHAR(50),
    UTSETTELSE_ARSAK            VARCHAR(50),
    OVERFORING_ARSAK            VARCHAR(50),
    MORS_AKTIVITET              VARCHAR(50),
    GRADERING_ARBEIDSTIDPROSENT NUMERIC,
    SAMTIDIG_UTTAKSPROSENT      NUMERIC,
    FLERBARNSDAGER              BOOLEAN,
    AKTIVITET_TYPE              VARCHAR(50),
    ARBEIDSGIVER_ID             VARCHAR(50),
    ARBEIDSGIVER_TYPE           VARCHAR(50),
    CONSTRAINT PK_SOKNADSUTTAKSPLAN_PERIODE PRIMARY KEY (ID),
    CONSTRAINT FK_SOKNADSUTTAKSPLAN_PERIODE_1 FOREIGN KEY (SOKNADSUTTAKSPLAN_ID) REFERENCES SOKNADSUTTAKSPLAN (ID)
);

CREATE SEQUENCE SEQ_SOKNADSUTTAKSPLAN_PERIODE MINVALUE 1000000 START WITH 1000000 INCREMENT BY 50 NO CYCLE;

CREATE INDEX IDX_SOKNADSUTTAKSPLAN_PERIODE_1 ON SOKNADSUTTAKSPLAN_PERIODE (SOKNADSUTTAKSPLAN_ID);

COMMENT ON TABLE SOKNADSUTTAKSPLAN IS 'Innsendt uttaksplan fra søknad om foreldrepenger';
COMMENT ON COLUMN SOKNADSUTTAKSPLAN.ID IS 'Teknisk identifikator for uttaksplanen';
COMMENT ON COLUMN SOKNADSUTTAKSPLAN.SAKSNUMMER IS 'Saksnummer til søkers sak';
COMMENT ON COLUMN SOKNADSUTTAKSPLAN.MOTTATT_TIDSPUNKT IS 'Tidspunkt uttaksplanen ble mottatt';
COMMENT ON COLUMN SOKNADSUTTAKSPLAN.ROLLE IS 'Rolle for søkeren';
COMMENT ON COLUMN SOKNADSUTTAKSPLAN.AKTIV IS 'Angir om uttaksplanen er aktiv for saken';

COMMENT ON TABLE SOKNADSUTTAKSPLAN_PERIODE IS 'Uttaksperioder i en søknadsuttaksplan';
COMMENT ON COLUMN SOKNADSUTTAKSPLAN_PERIODE.ID IS 'Teknisk identifikator for perioden';
COMMENT ON COLUMN SOKNADSUTTAKSPLAN_PERIODE.SOKNADSUTTAKSPLAN_ID IS 'Identifikator for uttaksplanen perioden tilhører';
COMMENT ON COLUMN SOKNADSUTTAKSPLAN_PERIODE.FOM IS 'Periodens startdato';
COMMENT ON COLUMN SOKNADSUTTAKSPLAN_PERIODE.TOM IS 'Periodens sluttdato';
COMMENT ON COLUMN SOKNADSUTTAKSPLAN_PERIODE.ROLLE IS 'Rolle for perioden';
COMMENT ON COLUMN SOKNADSUTTAKSPLAN_PERIODE.KONTO_TYPE IS 'Type uttakskonto';
COMMENT ON COLUMN SOKNADSUTTAKSPLAN_PERIODE.UTSETTELSE_ARSAK IS 'Årsak til utsettelse';
COMMENT ON COLUMN SOKNADSUTTAKSPLAN_PERIODE.OVERFORING_ARSAK IS 'Årsak til overføring';
COMMENT ON COLUMN SOKNADSUTTAKSPLAN_PERIODE.MORS_AKTIVITET IS 'Mors aktivitet';
COMMENT ON COLUMN SOKNADSUTTAKSPLAN_PERIODE.GRADERING_ARBEIDSTIDPROSENT IS 'Arbeidstidsprosent ved gradering';
COMMENT ON COLUMN SOKNADSUTTAKSPLAN_PERIODE.SAMTIDIG_UTTAKSPROSENT IS 'Prosent for samtidig uttak';
COMMENT ON COLUMN SOKNADSUTTAKSPLAN_PERIODE.FLERBARNSDAGER IS 'Angir om perioden gjelder flerbarnsdager';
COMMENT ON COLUMN SOKNADSUTTAKSPLAN_PERIODE.AKTIVITET_TYPE IS 'Type aktivitet i perioden';
COMMENT ON COLUMN SOKNADSUTTAKSPLAN_PERIODE.ARBEIDSGIVER_ID IS 'Organisasjonsnummer for organisasjon eller fødselsnummer for privat arbeidsgiver';
COMMENT ON COLUMN SOKNADSUTTAKSPLAN_PERIODE.ARBEIDSGIVER_TYPE IS 'Type arbeidsgiver';
